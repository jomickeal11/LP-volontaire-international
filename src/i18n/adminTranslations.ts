export function getAdminTranslations(lang?: string) {
  const l = (lang || "fr").toLowerCase()
  if (l.startsWith("en")) return adminTranslations.en
  if (l.startsWith("de")) return adminTranslations.de
  return adminTranslations.fr
}

export function getStatusLabel(status: string, lang?: string): string {
  const t = getAdminTranslations(lang)
  return (t.statuses as Record<string, string>)[status] || status
}

export function getPartnerStatusLabel(status: string, lang?: string): string {
  const t = getAdminTranslations(lang)
  return (t.partnerStatuses as Record<string, string>)[status] || status
}
